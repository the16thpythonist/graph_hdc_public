@experiment.hook("load_encoder", default=False, replace=True)
def load_encoder(e: Experiment, device: torch.device):
    """Load HyperNet and prune codebooks using chemical valence rules.

    Unlike the base experiment which scans a dataset for observed features,
    this uses chemical rules to enumerate all valid node feature tuples.
    This guarantees coverage of any valid molecule that BRICS can produce.

    The edge codebook is NOT pre-computed — it is only needed for
    decoding, not encoding.  Workers only encode, so skipping edge
    codebook pruning is both correct and saves memory.
    """
    if e.ENCODER_PATH and Path(e.ENCODER_PATH).exists():
        hypernet = load_hypernet(e.ENCODER_PATH, device=str(device))
    elif e.__TESTING__:
        from graph_hdc.hypernet.configs import get_config

        config = get_config("ZINC_SMILES_HRR_256_F64_5G1NG4")
        config.device = str(device)
        config.dtype = "float32"
        hypernet = HyperNet(config)
        hypernet = hypernet.to(device)
    else:
        raise ValueError(
            "ENCODER_PATH must be set to a valid HyperNet checkpoint path. "
            "Use --__TESTING__ True for quick tests without an encoder."
        )

    # Rebuild full codebook first (the checkpoint may have been saved pruned)
    e.log("Rebuilding full codebook from seed...")
    hypernet.rebuild_unpruned_codebook()

    # Determine RW configuration
    has_rw = hasattr(hypernet, "rw_config") and hypernet.rw_config.enabled
    if has_rw:
        num_rw_features = len(hypernet.rw_config.k_values)
        num_rw_bins = hypernet.rw_config.num_bins
        e.log(f"RRWP encoder: {num_rw_features} RW features, {num_rw_bins} bins each")
    else:
        num_rw_features = 0
        num_rw_bins = 0

    # Generate chemically valid node feature tuples
    valid_nodes = get_valid_node_tuples_with_rw(
        num_rw_features=num_rw_features,
        num_rw_bins=num_rw_bins,
    )
    base_count = len(get_valid_base_node_tuples())
    e.log(
        f"Chemical rules: {base_count} valid base tuples, "
        f"{len(valid_nodes)} total (with RW)"
    )

    # Prune node codebook to chemically valid tuples
    hypernet.limit_nodes_codebook(valid_nodes)
    e.log(f"Pruned nodes codebook: {hypernet.nodes_codebook.shape[0]} entries")
    e["config/nodes_codebook_size"] = hypernet.nodes_codebook.shape[0]

    # Prune edge codebook for non-RRWP encoders (small enough for Cartesian product).
    # For RRWP encoders, skip edge pruning — edge codebook is only needed for
    # decoding (not used in the forward/encode path) and the Cartesian product
    # with RW features would be too large.
    if not has_rw:
        valid_edges = get_valid_edge_pairs(valid_nodes)
        hypernet.limit_edges_codebook(valid_edges)
        e.log(f"Pruned edges codebook: {hypernet.edges_codebook.shape[0]} entries")
    else:
        # Full Cartesian product of edge pairs is infeasible for RRWP
        # (94K² = 9 billion entries).  Use incremental mode instead:
        # the edge codebook starts empty and grows as training batches
        # reveal new (src, dst) node-type pairs.
        hypernet.enable_incremental_edges()
        e.log("Edge codebook: incremental mode enabled (RRWP)")

    hypernet.eval()
    # Store on experiment so modify_callbacks can access it
    e._hypernet = hypernet
    return hypernet


@experiment.hook("load_and_encode_data", default=False, replace=True)
def load_and_encode_data(
    e: Experiment,
    hypernet: HyperNet,
    device: torch.device,
):
    """Build fragment library and load static ZINC validation set.

    Both the fragment library construction and validation encoding are
    cached via ``@e.cache.cached`` to skip expensive recomputation on
    subsequent runs with the same configuration.

    Training data is streamed (no static train_encoded), so we return
    None for train_encoded.  The ``create_data_loaders`` hook handles
    creating the streaming train loader.

    Returns:
        (None, valid_encoded) where valid_encoded is a list of Data objects
        with node_terms (= edge_terms, swapped) and graph_terms.
    """
    import time

    # -----------------------------------------------------------------
    # Build fragment library (cached)
    # -----------------------------------------------------------------
    e.log("\nBuilding fragment library from dataset...")

    testing = e.__TESTING__

    @e.cache.cached(
        name="fragment_library",
        scope=lambda _e: (
            "brics_fragments",
            _e.DATASET.lower(),
            f"enum_{_e.ENUMERATE_ATTACHMENTS}",
            f"maxvar_{_e.ENUM_MAX_VARIANTS_PER_FRAGMENT}",
        ),
    )
    def build_fragment_library():
        # Build from ALL splits so the fragment library covers the full
        # chemical space of the dataset, not just the training set.
        all_data = []
        for split in ("train", "valid", "test"):
            ds = get_split(split, dataset=e.DATASET.lower())
            all_data.extend(ds)
        if testing:
            all_data = all_data[:200]
        e.log(f"  Dataset size (all splits): {len(all_data)}")

        lib = FragmentLibrary(min_atoms=2, max_atoms=30)
        lib.build_from_dataset(all_data, show_progress=True)
        e.log(f"  Fragment library: {lib.num_fragments} fragments")

        if e.ENUMERATE_ATTACHMENTS:
            n_before = lib.num_fragments
            n_added = lib.expand_with_enumerated_positions(
                max_new_points=e.ENUM_MAX_VARIANTS_PER_FRAGMENT,
            )
            e.log(
                f"  Enumerated attachment expansion: {n_before} -> "
                f"{lib.num_fragments} fragments (+{n_added} variants)"
            )

        return lib

    t0 = time.time()
    fragment_library = build_fragment_library()
    e.log(
        f"Fragment library ready: {fragment_library.num_fragments} fragments "
        f"({time.time() - t0:.1f}s)"
    )
    e["data/num_fragments"] = fragment_library.num_fragments

    # Save fragment library to experiment output dir
    library_path = Path(e.path) / "fragment_library.pkl"
    fragment_library.save(library_path)
    e.log(f"Saved fragment library to: {library_path}")

    # Save the chemically-pruned encoder for workers.  The node codebook
    # covers all valid chemistry (from load_encoder hook), so workers
    # can encode any BRICS-generated molecule.
    encoder_path = Path(e.path) / "hypernet_encoder.ckpt"
    hypernet.save(encoder_path)
    e.log(f"Saved encoder for workers: {encoder_path}")
    e["results/encoder_path"] = str(encoder_path)

    # Store on experiment for use by create_data_loaders
    e._fragment_library = fragment_library
    e._encoder_path = encoder_path

    # -----------------------------------------------------------------
    # Seed edge codebook from dataset (cached)
    # -----------------------------------------------------------------
    has_rw = hasattr(hypernet, "rw_config") and hypernet.rw_config.enabled
    if getattr(hypernet, "_incremental_edges", False):
        e.log("\nSeeding edge codebook from dataset...")

        @e.cache.cached(
            name="dataset_edge_pairs",
            scope=lambda _e: (
                "edge_pairs",
                _e.DATASET.lower(),
                Path(_e.ENCODER_PATH).stem if _e.ENCODER_PATH else "test",
            ),
        )
        def collect_dataset_edge_pairs():
            """Scan all dataset molecules and collect observed edge pairs.

            Applies RW augmentation to match the node feature tuples that
            streaming workers produce, so the seeded edge pairs are in the
            same feature space as incrementally discovered ones.
            """
            all_data = []
            for split in ("train", "valid", "test"):
                ds = get_split(split, dataset=e.DATASET.lower())
                all_data.extend(ds)
            if testing:
                all_data = all_data[:200]

            edge_pairs: set[tuple[tuple[int, ...], tuple[int, ...]]] = set()

            if has_rw:
                from graph_hdc.utils.rw_features import augment_data_with_rw_np

                rw_k = hypernet.rw_config.k_values
                rw_bins = hypernet.rw_config.num_bins
                rw_boundaries = hypernet.rw_config.bin_boundaries
                rw_clip_range = hypernet.rw_config.clip_range

            for data in all_data:
                if data.edge_index is None or data.edge_index.numel() == 0:
                    continue

                d = data.clone()
                if has_rw:
                    d = augment_data_with_rw_np(
                        d,
                        k_values=rw_k,
                        num_bins=rw_bins,
                        bin_boundaries=rw_boundaries,
                        clip_range=rw_clip_range,
                    )

                node_tuples = [
                    tuple(int(v) for v in row)
                    for row in d.x.tolist()
                ]
                for e_idx in range(d.edge_index.size(1)):
                    src = d.edge_index[0, e_idx].item()
                    dst = d.edge_index[1, e_idx].item()
                    edge_pairs.add((node_tuples[src], node_tuples[dst]))

            return edge_pairs

        t0 = time.time()
        seed_pairs = collect_dataset_edge_pairs()
        n_seeded = hypernet.register_edges(seed_pairs)
        total = hypernet._edges_codebook.shape[0]
        e.log(
            f"Edge codebook seeded: {n_seeded} edge types from "
            f"{len(seed_pairs)} observed pairs (total: {total}, "
            f"{time.time() - t0:.1f}s)"
        )
        e["config/edge_codebook_seeded"] = total

    # -----------------------------------------------------------------
    # Static validation set (cached)
    # -----------------------------------------------------------------
    e.log("\nLoading ZINC validation set...")

    @e.cache.cached(
        name="valid_encoded",
        scope=lambda _e: (
            "valid_encoding",
            _e.DATASET.lower(),
            Path(_e.ENCODER_PATH).stem if _e.ENCODER_PATH else "test",
            f"n_{_e.NUM_VALID_SAMPLES or 'all'}",
        ),
    )
    def encode_validation_set():
        valid_ds = get_split("valid", dataset=e.DATASET.lower())

        if testing:
            valid_ds = valid_ds[:16]
        elif e.NUM_VALID_SAMPLES is not None:
            valid_ds = valid_ds[: e.NUM_VALID_SAMPLES]

        e.log(f"  Validation: {len(valid_ds)}")
        e.log("  Computing HDC encodings for validation set...")
        encoded = post_compute_encodings(
            valid_ds, hypernet, device=device, batch_size=e.ENCODER_BATCH_SIZE,
        )
        torch.cuda.empty_cache()
        e.log(f"  Encoded: {len(encoded)} validation samples")
        return encoded

    t0 = time.time()
    valid_encoded = encode_validation_set()
    e.log(
        f"Validation set ready: {len(valid_encoded)} samples "
        f"({time.time() - t0:.1f}s)"
    )

    # Swap edge_terms -> node_terms
    for d in valid_encoded:
        d.node_terms = d.edge_terms

    return None, valid_encoded


@experiment.hook("create_data_loaders", default=False, replace=True)
def create_data_loaders(e: Experiment, train_encoded, valid_encoded):
    """Create streaming train loader and static validation loader.

    ``train_encoded`` is None (streaming mode).  The fragment library
    and encoder path are retrieved from the experiment object.
    """
    fragment_library = e._fragment_library
    encoder_path = e._encoder_path

    # -----------------------------------------------------------------
    # Streaming train loader
    # -----------------------------------------------------------------
    e.log("\nCreating streaming fragment dataset...")

    streaming_dataset = StreamingAEDataset(
        fragment_library=fragment_library,
        hypernet_checkpoint_path=str(encoder_path),
        buffer_size=e.BUFFER_SIZE,
        num_workers=e.NUM_FRAGMENT_WORKERS,
        fragments_range=(e.FRAGMENTS_RANGE_MIN, e.FRAGMENTS_RANGE_MAX),
        max_nodes=e.MAX_GENERATED_NODES,
        encoding_batch_size=e.ENCODING_BATCH_SIZE,
        prefill_fraction=e.PREFILL_FRACTION,
    )

    train_loader = StreamingAEDataLoader(
        dataset=streaming_dataset,
        batch_size=e.BATCH_SIZE,
        steps_per_epoch=e.STEPS_PER_EPOCH,
    )

    e.log(
        f"Streaming loader: {e.STEPS_PER_EPOCH} steps/epoch, "
        f"batch_size={e.BATCH_SIZE}, {e.NUM_FRAGMENT_WORKERS} workers, "
        f"buffer={e.BUFFER_SIZE}"
    )

    # Test the pipeline
    e.log("Testing streaming pipeline (2 batches)...")
    try:
        train_loader.test_iteration(num_batches=2)
        e.log("Streaming pipeline test passed!")
    except Exception as ex:
        e.log(f"ERROR: Streaming pipeline test failed: {ex}")
        train_loader.stop()
        raise

    # Store for cleanup callback
    e._streaming_train_loader = train_loader

    # -----------------------------------------------------------------
    # Static validation loader
    # -----------------------------------------------------------------
    valid_loader = DataLoader(
        valid_encoded,
        batch_size=e.BATCH_SIZE,
        shuffle=False,
        num_workers=0,
    )

    return train_loader, valid_loader


