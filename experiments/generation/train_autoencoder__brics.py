@experiment.testing
def testing(e: Experiment):
    """Quick test mode with reduced parameters for streaming."""
    # Use auto-created small encoder (avoids slow RW scan on full ZINC)
    e.ENCODER_PATH = ""
    e.EPOCHS = 2
    e.STEPS_PER_EPOCH = 5
    e.BUFFER_SIZE = 100
    e.NUM_FRAGMENT_WORKERS = 1
    e.PREFILL_FRACTION = 0.05
    e.BATCH_SIZE = 16
    e.RECON_EVAL_EVERY_N_EPOCHS = 100  # Skip molecular recon in tests
    e.ENUMERATE_ATTACHMENTS = False


experiment.run_if_main()
