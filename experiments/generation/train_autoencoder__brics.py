#!/usr/bin/env python
"""
Train AE/VAE on BRICS-generated molecules (streaming).

Child experiment of ``train_autoencoder.py`` that replaces the static
dataset with an infinite stream of molecules generated by combining
BRICS fragments on-the-fly.  Training data is never exhausted; each
epoch is defined as a fixed number of steps (``STEPS_PER_EPOCH``).

Validation uses the static ZINC validation set (same as the base
experiment) to provide a stable reconstruction quality reference.

The encoder must be created with RRWP features using
``experiments/scripts/create_rrwp_encoder.py``.

Usage:
    # Quick test
    python train_autoencoder__brics.py --__TESTING__ True

    # Full training (AE)
    python train_autoencoder__brics.py --__DEBUG__ False \\
        --ENCODER_PATH /path/to/encoder.ckpt

    # Full training (VAE)
    python train_autoencoder__brics.py --__DEBUG__ False --VARIATIONAL True \\
        --ENCODER_PATH /path/to/encoder.ckpt
"""
