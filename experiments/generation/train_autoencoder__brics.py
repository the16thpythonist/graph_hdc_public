@experiment.hook("modify_callbacks", default=False, replace=True)
def modify_callbacks(e: Experiment, callbacks, train_loader):
    """Add edge codebook update and streaming cleanup callbacks."""
    hypernet = e._hypernet
    # Insert edge codebook updater at the front so it runs before
    # ReconstructionEvalCallback's on_validation_epoch_start/end.
    if getattr(hypernet, "_incremental_edges", False):
        callbacks.insert(
            0,
            EdgeCodebookUpdateCallback(
                experiment=e,
                hypernet=hypernet,
                streaming_loader=train_loader,
            ),
        )
    callbacks.append(StreamingDatasetCleanupCallback(train_loader))
    return callbacks


