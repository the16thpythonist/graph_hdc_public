class StreamingDatasetCleanupCallback(Callback):
    """Cleanup streaming dataset workers on training end."""

    def __init__(self, streaming_loader: StreamingAEDataLoader):
        super().__init__()
        self.streaming_loader = streaming_loader

    def on_train_end(self, trainer, pl_module):
        self.streaming_loader.stop()


class EdgeCodebookUpdateCallback(Callback):
    """Drain edge pairs from the streaming loader each epoch and register
    them in the HyperNet's incremental edge codebook.

    Must be added **before** ``ReconstructionEvalCallback`` in the callback
    list so the codebook is up-to-date when decoding runs.
    """

    def __init__(
        self,
        experiment: Experiment,
        hypernet: HyperNet,
        streaming_loader: StreamingAEDataLoader,
    ):
        super().__init__()
        self.experiment = experiment
        self.hypernet = hypernet
        self.streaming_loader = streaming_loader

    def on_validation_epoch_start(self, trainer, pl_module):
        if trainer.sanity_checking:
            return
        pairs = self.streaming_loader.drain_edge_pairs()
        if not pairs:
            return
        n_new = self.hypernet.register_edges(pairs)
        total = self.hypernet._edges_codebook.shape[0]
        self.experiment.log(
            f"[EdgeCodebook] +{n_new} new edge types from "
            f"{len(pairs)} observed pairs (total: {total})"
        )


